terminal_sonoqr AS (
    SELECT
        trim(cast(last_terminal_match_merchant_id AS varchar)) AS merchant_id,
        count(DISTINCT trim(cast(terminal_serial AS varchar))) AS cantidad_sonoqr,
        array_join(array_agg(DISTINCT trim(cast(terminal_serial AS varchar))), ', ') AS seriales_sonoqr,
        array_join(array_agg(DISTINCT coalesce(current_terminal_status, 'SIN_ESTADO')), ' | ') AS estados_terminal,
        array_join(array_agg(DISTINCT coalesce(current_merchant_matched, 'SIN_MATCH_ACTUAL')), ' | ') AS merchants_actualmente_asociados,
        array_join(array_agg(DISTINCT coalesce(last_terminal_match_status, 'SIN_ESTADO_MATCH')), ' | ') AS estados_ultima_asociacion,
        min(_1st_match_date_current_merchant) AS primera_asociacion_actual,
        max(last_terminal_match_date) AS ultima_asociacion,
        min(_1st_transaction_approved_date) AS primera_tx_sonoqr,
        max(last_transaction_approved_date) AS ultima_tx_sonoqr
    FROM awsdatacatalog.bold_gold_terminals.mart_terminal_enrich
    WHERE upper(trim(coalesce(model_name_category, ''))) = 'SONOQR'
      AND last_terminal_match_merchant_id IS NOT NULL
      AND terminal_serial IS NOT NULL
    GROUP BY 1
),
cuentas AS (
    SELECT
        trim(cast(merchant_id AS varchar)) AS merchant_id,
        array_join(array_agg(DISTINCT coalesce(bank_account_name, 'SIN_NOMBRE_BANCO')), ' | ') AS bancos_registrados,
        array_join(array_agg(DISTINCT coalesce(cast(bank_account_id AS varchar), 'SIN_ID_CUENTA')), ' | ') AS ids_cuenta_registrados,
        max(CASE WHEN upper(trim(coalesce(bank_account_name, ''))) = 'BOLD. C.F.' THEN 1 ELSE 0 END) AS tiene_cuenta_bold,
        array_join(array_agg(DISTINCT CASE WHEN upper(trim(coalesce(bank_account_name, ''))) = 'BOLD. C.F.' THEN cast(bank_account_id AS varchar) END), ' | ') AS ids_cuenta_bold
    FROM awsdatacatalog.bold_gold_growth.dim_merchant_onboarding
    WHERE merchant_id IS NOT NULL
    GROUP BY 1
),
merchant_profile AS (
    SELECT
        trim(cast(id AS varchar)) AS merchant_id,
        max(name) AS merchant_name
    FROM awsdatacatalog.bold_gold_payments.dim_merchant
    GROUP BY 1
)
SELECT
    i.source_row,
    i.merchant_id,
    p.merchant_name,
    CASE WHEN t.merchant_id IS NOT NULL THEN 'SI' ELSE 'NO' END AS tiene_sonoqr,
    coalesce(t.cantidad_sonoqr, 0) AS cantidad_sonoqr,
    t.seriales_sonoqr,
    t.estados_terminal,
    t.merchants_actualmente_asociados,
    t.estados_ultima_asociacion,
    t.primera_asociacion_actual,
    t.ultima_asociacion,
    t.primera_tx_sonoqr,
    t.ultima_tx_sonoqr,
    CASE WHEN coalesce(c.tiene_cuenta_bold, 0) = 1 THEN 'SI' ELSE 'NO' END AS tiene_cuenta_bold,
    coalesce(c.ids_cuenta_bold, 'SIN_CUENTA_BOLD') AS numero_cuenta_bold,
    c.bancos_registrados,
    c.ids_cuenta_registrados,
    CASE
        WHEN p.merchant_id IS NULL THEN 'SIN_MATCH_DIM_MERCHANT'
        WHEN t.merchant_id IS NULL AND coalesce(c.tiene_cuenta_bold, 0) = 0 THEN 'SIN_SONOQR_Y_SIN_CUENTA_BOLD'
        WHEN t.merchant_id IS NOT NULL AND coalesce(c.tiene_cuenta_bold, 0) = 1 THEN 'SONOQR_CON_CUENTA_BOLD'
        WHEN t.merchant_id IS NOT NULL AND coalesce(c.tiene_cuenta_bold, 0) = 0 THEN 'SONOQR_PRESENTE_SIN_CUENTA_BOLD_REVISAR'
        ELSE 'SIN_SONOQR_CON_CUENTA_BOLD'
    END AS estado_conciliacion
FROM input_merchants i
LEFT JOIN merchant_profile p ON p.merchant_id = i.merchant_id
LEFT JOIN terminal_sonoqr t ON t.merchant_id = i.merchant_id
LEFT JOIN cuentas c ON c.merchant_id = i.merchant_id
ORDER BY i.source_row;
